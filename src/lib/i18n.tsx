type Ctx = { lang: Lang; setLang: (l: Lang) => void; t: (key: string) => string };
const I18nCtx = createContext<Ctx | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>("en");
  useEffect(() => {
    try {
      const saved = localStorage.getItem("sabacho-lang") as Lang | null;
      if (saved && dicts[saved]) setLang(saved);
    } catch {}
  }, []);
  useEffect(() => {
    try { localStorage.setItem("sabacho-lang", lang); } catch {}
    if (typeof document !== "undefined") document.documentElement.lang = lang;
  }, [lang]);
  const t = (k: string) => dicts[lang][k] ?? dicts.en[k] ?? k;
  return <I18nCtx.Provider value={{ lang, setLang, t }}>{children}</I18nCtx.Provider>;
}

export function useI18n() {
  const c = useContext(I18nCtx);
  if (!c) throw new Error("useI18n outside provider");
  return c;
}

export function pickLang<T extends Record<string, unknown>>(row: T, base: string, lang: Lang): string {
  const key = lang === "en" ? base : `${base}_${lang}`;
  const v = (row as Record<string, unknown>)[key];
  if (typeof v === "string" && v.trim()) return v;
  const fallback = (row as Record<string, unknown>)[base];
  return typeof fallback === "string" ? fallback : "";
}